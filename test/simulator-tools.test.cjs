'use strict';
const assert=require('assert'),path=require('path'),os=require('os'),vm=require('vm'),{pathToFileURL}=require('url');
const launcher=require('../tools/simulator.cjs'),qa=require('../tools/simulator-qa.cjs');
const config=JSON.parse(JSON.stringify(require('../config.example.json'))),root=path.join(os.tmpdir(),'viewer-project-fixture');
config.development.simulatorExecutable=path.join(os.tmpdir(),'simulator-fixture.exe');
config.development.simulatorServiceDirectory=path.join(os.tmpdir(),'viewer-service-fixture');
const plan=launcher.createLaunchPlan(root,config,{debug:true});assert.strictEqual(plan.debugPort,9224);assert.strictEqual(plan.debug,true);
assert(!('recorder' in plan));assert(!('television' in plan));
assert.throws(()=>launcher.parseArguments(['--tv']));
const unsafe=JSON.parse(JSON.stringify(config));unsafe.development.simulatorServiceDirectory=path.join(root,'src');assert.throws(()=>launcher.createLaunchPlan(root,unsafe));
assert.strictEqual(qa.debuggerUrl('ws://localhost:9224/devtools/page/fixture',9224),'ws://127.0.0.1:9224/devtools/page/fixture');
assert.throws(()=>qa.debuggerUrl('ws://example.invalid:9224/devtools/page/fixture',9224));
assert.throws(()=>qa.debuggerUrl('ws://127.0.0.1:9225/devtools/page/fixture',9224));
assert.throws(()=>qa.parseArguments(['--soak-seconds','0']));
assert.strictEqual(qa.parseArguments(['--ui-only']).uiOnly,true);
assert.strictEqual(typeof qa.readTargetsWithRetry,'function');
const session={appId:launcher.APP_ID,serviceId:launcher.SERVICE_ID,sessionId:'1'.repeat(32),appPath:plan.appPath,debugPort:9224,debug:true};
assert.strictEqual(qa.validateSession(session,root,9224),session);
const url=pathToFileURL(path.join(plan.appPath,'index.html')).href;
assert(qa.isOwnPage(url,plan.appPath));assert(!qa.isOwnPage('https://example.invalid/',plan.appPath));
const expression=qa.ownedExpression('42',session);
assert.strictEqual(vm.runInNewContext(expression,{window:{webOSSystem:{launchParams:JSON.stringify({simulatorSession:session.sessionId})}},location:{href:url},URL}),42);
assert.throws(()=>vm.runInNewContext(expression,{window:{webOSSystem:{launchParams:'{}'}},location:{href:url},URL}),/owned simulator/);
console.log('Simulator tooling rejects external targets, mismatched sessions and unsafe paths without launching or network access.');
